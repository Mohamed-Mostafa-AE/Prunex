#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

export function sigmoid(value) {
  if (value >= 0) return 1 / (1 + Math.exp(-Math.min(value, 40)));
  const exp = Math.exp(Math.max(value, -40));
  return exp / (1 + exp);
}

export function fitCalibration(samples, { epochs = 4000, learningRate = 0.015, l2 = 0.0001 } = {}) {
  if (!Array.isArray(samples) || samples.length < 100) {
    throw new Error("At least 100 labeled positions are required; use a held-out, representative PGN corpus.");
  }
  const clean = samples.map((sample, index) => {
    const scoreCp = Number(sample.scoreCp);
    const result = Number(sample.result);
    if (!Number.isFinite(scoreCp) || !Number.isFinite(result) || result < 0 || result > 1) {
      throw new Error("Invalid sample at row " + (index + 1) + ": expected scoreCp and result in [0, 1].");
    }
    return {
      x: Math.max(-10, Math.min(10, scoreCp / 400)),
      y: result,
      gameId: sample.gameId == null ? null : String(sample.gameId)
    };
  });
  // Keep all positions from a game in one partition to avoid leakage.
  const gamePartitions = new Map();
  for (const sample of clean) {
    if (sample.gameId && !gamePartitions.has(sample.gameId)) {
      let hash = 2166136261;
      for (const char of sample.gameId) hash = Math.imul(hash ^ char.charCodeAt(0), 16777619) >>> 0;
      gamePartitions.set(sample.gameId, hash % 5 === 0 ? "validation" : "train");
    }
  }
  const train = clean.filter((sample, index) => sample.gameId
    ? gamePartitions.get(sample.gameId) === "train" : index % 5 !== 0);
  const validation = clean.filter((sample, index) => sample.gameId
    ? gamePartitions.get(sample.gameId) === "validation" : index % 5 === 0);
  if (train.length < 80 || validation.length < 20) throw new Error("Dataset split is too small.");
  let slope = 1;
  let intercept = 0;
  for (let epoch = 0; epoch < epochs; epoch += 1) {
    let slopeGradient = 0;
    let interceptGradient = 0;
    for (const sample of train) {
      const error = sigmoid(slope * sample.x + intercept) - sample.y;
      slopeGradient += error * sample.x;
      interceptGradient += error;
    }
    slopeGradient = slopeGradient / train.length + l2 * (slope - 1);
    interceptGradient /= train.length;
    const rate = learningRate / Math.sqrt(1 + epoch / 250);
    slope = Math.max(0.05, Math.min(5, slope - rate * slopeGradient));
    intercept = Math.max(-2, Math.min(2, intercept - rate * interceptGradient));
  }
  const epsilon = 1e-12;
  const validationLogLoss = validation.reduce((sum, sample) => {
    const p = Math.max(epsilon, Math.min(1 - epsilon, sigmoid(slope * sample.x + intercept)));
    return sum - (sample.y * Math.log(p) + (1 - sample.y) * Math.log(1 - p));
  }, 0) / validation.length;
  return {
    model: "logistic-expected-points-v1",
    slope,
    intercept,
    trainingSamples: train.length,
    validationSamples: validation.length,
    validationLogLoss,
    trained: true
  };
}

function readJsonl(path) {
  return readFileSync(path, "utf8").split(/\r?\n/).filter(Boolean).map((line, index) => {
    try { return JSON.parse(line); }
    catch { throw new Error("Invalid JSON on dataset line " + (index + 1)); }
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const input = process.argv[2];
  if (!input) {
    console.error("Usage: node scripts/calibrate-evaluation.mjs <positions.jsonl> [output-module.js]");
    process.exitCode = 2;
  } else {
    const output = resolve(process.argv[3] || "src/evaluation-calibration.js");
    const result = fitCalibration(readJsonl(resolve(input)));
    const source = "// Generated by scripts/calibrate-evaluation.mjs. Do not hand-edit.\n" +
      "export const evaluationCalibration = Object.freeze(" +
      JSON.stringify(result, null, 2) + ");\n";
    writeFileSync(output, source);
    console.log(JSON.stringify({ output, ...result }, null, 2));
  }
}
